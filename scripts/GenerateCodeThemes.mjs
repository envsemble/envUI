// Generates packages/ui/src/content/internal/CodeDiffTints.ts: how Diffs tints the lines and words
// a diff adds and removes, read from Diffs' style sheet. The code themes make their token colors
// readable where they load (packages/ui/src/content/internal/CodeThemes.ts), from whichever Pierre
// themes an application installs; for code diffs they also need the backgrounds Diffs gives changed
// lines, which Diffs mixes in its style sheet from the theme's addition and deletion colors:
//
// - a changed line's background is code's background mixed in Lab with the change color;
// - an emphasized word's background is the change color at an opacity over the line's.
//
//   node scripts/GenerateCodeThemes.mjs [--check]
//
// --check writes nothing and fails when the committed file differs from a fresh read, as after an
// update of @pierre/diffs. tests/CodeHighlighting.test.mjs checks the highlighted colors.
import { readFile, writeFile } from 'node:fs/promises';
import { resolve } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';
import { format, resolveConfig } from 'prettier';

const repositoryRoot = fileURLToPath(new URL('../', import.meta.url));
export const tintsFile = resolve(
  repositoryRoot,
  'packages/ui/src/content/internal/CodeDiffTints.ts',
);

/**
 * How Diffs tints changed lines, from its style sheet: the share of the change color mixed into a
 * line's background in Lab, and the opacity of the change color over it for emphasized words, for
 * the light and the dark theme.
 */
export async function diffTints() {
  // The style sheet beside the package's entry point, which its exports do not list.
  const style = await readFile(new URL('./style.js', import.meta.resolve('@pierre/diffs')), 'utf8');
  const kind = (name) => {
    const line = style.match(
      new RegExp(
        String.raw`--diffs-bg-${name}:var\(--diffs-bg-${name}-override,light-dark\(color-mix\(in lab, var\(--diffs-bg\) ([\d.]+)%, var\(--diffs-${name}-base\)\),color-mix\(in lab, var\(--diffs-bg\) ([\d.]+)%`,
      ),
    );
    const emphasis = style.match(
      new RegExp(
        String.raw`--diffs-bg-${name}-emphasis:var\(--diffs-bg-${name}-emphasis-override,light-dark\(rgb\(from var\(--diffs-${name}-base\) r g b / ([\d.]+)\),rgb\(from var\(--diffs-${name}-base\) r g b / ([\d.]+)\)`,
      ),
    );
    if (!line || !emphasis)
      throw new Error(`Diffs' style sheet no longer tints ${name}s as this script reads it.`);
    const round = (value) => Math.round(value * 1e6) / 1e6;
    return {
      light: { mix: round(1 - Number(line[1]) / 100), alpha: Number(emphasis[1]) },
      dark: { mix: round(1 - Number(line[2]) / 100), alpha: Number(emphasis[2]) },
    };
  };
  return { addition: kind('addition'), deletion: kind('deletion') };
}

/** The generated module, as the committed file must read. */
export async function tintsSource() {
  const text = `// Generated by scripts/GenerateCodeThemes.mjs from @pierre/diffs' style sheet; do not edit.

/** The tint of a changed line in one app theme: see the generator. */
export interface DiffTint {
  /** The share of the change color mixed in Lab into code's background, for the line. */
  mix: number;
  /** The opacity of the change color over the line's background, for an emphasized word. */
  alpha: number;
}

/** How Diffs tints the lines and words a diff adds and removes, in each app theme. */
export const diffTints: Record<'addition' | 'deletion', Record<'light' | 'dark', DiffTint>> = ${JSON.stringify(await diffTints())};
`;
  return format(text, { ...(await resolveConfig(tintsFile)), filepath: tintsFile });
}

async function main() {
  const expected = await tintsSource();
  if (process.argv.includes('--check')) {
    const current = await readFile(tintsFile, 'utf8').catch(() => '');
    if (current !== expected) {
      console.error(`${tintsFile} is stale: run node scripts/GenerateCodeThemes.mjs.`);
      process.exitCode = 1;
    } else console.log("The code diffs' tints match Diffs' style sheet.");
    return;
  }
  await writeFile(tintsFile, expected);
  console.log(`Wrote ${tintsFile}.`);
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) await main();
