import { resolve } from 'node:path';
import { Project } from 'ts-morph';
import { GeneratedOutput } from '../build/GeneratedFiles.ts';
import { libraryEntryPoints } from './LibraryEntryPoints.ts';
import { isRuntime, PropsReader } from './PropsReader.ts';
import { libraryDirectory, propsFile } from '../RepositoryPaths.ts';

const undocumentedEntryPoints = new Set(['@envsemble/envui/messages']);

export function extractProps() {
  const project = new Project({ tsConfigFilePath: resolve(libraryDirectory, 'tsconfig.json') });
  const entryPoints = libraryEntryPoints()
    .filter(({ specifier }) => !undocumentedEntryPoints.has(specifier))
    .map(({ specifier, file }) => ({ specifier, source: project.getSourceFileOrThrow(file) }));
  const publicNames = new Set(
    entryPoints.flatMap(({ source }) => [...source.getExportedDeclarations().keys()]),
  );
  const reader = new PropsReader(project.getTypeChecker().compilerObject, publicNames);
  for (const { specifier, source } of entryPoints)
    for (const [name, [declaration]] of source.getExportedDeclarations())
      if (isRuntime(declaration)) reader.describe(name, declaration, specifier);
  const sorted = [...reader.exportsByName].sort(([a], [b]) => (a < b ? -1 : a > b ? 1 : 0));
  return {
    $comment:
      'Generated by scripts/docs/ExtractProps.ts from the TypeScript source of the public entry points; do not edit. Run npm run docs:props after changing a public component.',
    exports: Object.fromEntries(sorted),
  };
}

export function serializeProps(props: unknown) {
  return `${JSON.stringify(props, null, 2)}\n`;
}

if (import.meta.main) {
  const check = process.argv.includes('--check');
  const serialized = serializeProps(extractProps());
  const output = new GeneratedOutput({ check, regenerate: 'npm run docs:props' });
  output.writeOrCheck(propsFile, serialized);
  output.exitIfStale();
  if (check) console.log('docs/generated/props.json matches the TypeScript source.');
  else {
    const count = Object.keys(JSON.parse(serialized).exports).length;
    console.log(`Extracted ${count} public exports into docs/generated/props.json.`);
  }
}
